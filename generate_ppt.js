
const pptxgen = require("pptxgenjs");
const path = require("path");

const API_URL = "http://127.0.0.1:8000/generate-slides";

// Demo webpage content.
// Later, Chrome extension nunchi extracted webpage text pampinchachu.
const webpageText = `
Solar energy comes from sunlight.
Solar panels convert sunlight into electricity.
Solar energy is renewable.
Solar electricity production depends on sunlight and weather.
Solar power can reduce dependence on fossil fuels.
`;

async function main() {
  console.log("Requesting AI-generated slides...");

  // Step 1: Ask the FastAPI backend to generate slides.
  const response = await fetch(API_URL, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      "Accept": "application/json"
    },
    body: JSON.stringify({ text: webpageText })
  });

  if (!response.ok) {
    const errorText = await response.text();
    throw new Error(
      `AI API failed (${response.status}): ${errorText}`
    );
  }

  const data = await response.json();

  if (!Array.isArray(data.slides) || data.slides.length === 0) {
    throw new Error("AI response contains no slides.");
  }

  console.log(`Received ${data.slides.length} slides.`);

  // Step 2: Create an editable PowerPoint.
  const pptx = new pptxgen();
  pptx.layout = "LAYOUT_WIDE";
  pptx.author = "Local Vision AI";
  pptx.subject = "AI-generated webpage presentation";
  pptx.title = data.presentation_title || "AI Presentation";
  pptx.company = "Local Vision AI";

  pptx.theme = {
    headFontFace: "Aptos Display",
    bodyFontFace: "Aptos",
    lang: "en-US"
  };

  const W = 13.333;
  const H = 7.5;

  data.slides.forEach((item, index) => {
    const slide = pptx.addSlide();

    slide.background = { color: "F5F7FB" };

    // Top accent bar.
    slide.addShape(pptx.ShapeType.rect, {
      x: 0,
      y: 0,
      w: W,
      h: 0.13,
      line: { color: "2563EB", transparency: 100 },
      fill: { color: "2563EB" }
    });

    // Presentation title on every slide.
    slide.addText(
      data.presentation_title || "Local Vision AI",
      {
        x: 0.65,
        y: 0.32,
        w: 11.9,
        h: 0.3,
        fontFace: "Aptos",
        fontSize: 11,
        color: "64748B",
        margin: 0,
        breakLine: false
      }
    );

    // Slide heading.
    slide.addText(String(item.title || `Slide ${index + 1}`), {
      x: 0.65,
      y: 0.85,
      w: 12,
      h: 0.85,
      fontFace: "Aptos Display",
      fontSize: 28,
      bold: true,
      color: "14213D",
      margin: 0.04,
      valign: "mid",
      fit: "shrink"
    });

    // Short underline.
    slide.addShape(pptx.ShapeType.rect, {
      x: 0.68,
      y: 1.77,
      w: 0.85,
      h: 0.06,
      line: { color: "2563EB", transparency: 100 },
      fill: { color: "2563EB" }
    });

    // Editable bullet text.
    const bullets = Array.isArray(item.bullets)
      ? item.bullets.slice(0, 5)
      : [];

    bullets.forEach((bullet, bulletIndex) => {
      const y = 2.12 + bulletIndex * 0.91;

      slide.addText(`•  ${String(bullet)}`, {
        x: 0.85,
        y,
        w: 11.55,
        h: 0.72,
        fontFace: "Aptos",
        fontSize: 20,
        color: "263449",
        margin: 0.08,
        valign: "mid",
        breakLine: false,
        fit: "shrink"
      });
    });

    // Footer and slide number.
    slide.addShape(pptx.ShapeType.line, {
      x: 0.65,
      y: 6.92,
      w: 12.0,
      h: 0,
      line: { color: "D8DEE9", width: 1 }
    });

    slide.addText("Generated by Local Vision AI", {
      x: 0.68,
      y: 7.02,
      w: 7,
      h: 0.22,
      fontSize: 9,
      color: "64748B",
      margin: 0
    });

    slide.addText(`${index + 1} / ${data.slides.length}`, {
      x: 11.5,
      y: 7.02,
      w: 1.1,
      h: 0.22,
      fontSize: 9,
      color: "64748B",
      align: "right",
      margin: 0
    });

    // Add speaker notes when supported by the installed PptxGenJS version.
    if (
      item.speaker_notes &&
      typeof slide.addNotes === "function"
    ) {
      slide.addNotes(String(item.speaker_notes));
    }
  });

  // Step 3: Save the PowerPoint in the project folder.
  const outputFile = path.join(
    __dirname,
    "ai_generated_presentation.pptx"
  );

  await pptx.writeFile({ fileName: outputFile });

  console.log("SUCCESS! PowerPoint created:");
  console.log(outputFile);
  console.log(`Total slides: ${data.slides.length}`);
}

main().catch((error) => {
  console.error("PowerPoint generation failed:");
  console.error(error.message);
  process.exitCode = 1;
});
